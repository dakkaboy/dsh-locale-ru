// Coverage check against the batch: same namespaces and keys.
const problems = [];
for (const ns of Object.keys(batch)) {
  if (!out[ns]) { problems.push(`missing namespace ${ns}`); continue; }
  for (const key of Object.keys(batch[ns])) if (!(key in out[ns])) problems.push(`${ns}/${key} missing`);
  for (const key of Object.keys(out[ns])) if (!(key in batch[ns])) problems.push(`${ns}/${key} extra`);
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
fs.writeFileSync('translate/ru-G16.json', JSON.stringify(out, null, 2) + '\n');
